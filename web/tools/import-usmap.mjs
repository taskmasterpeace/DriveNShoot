#!/usr/bin/env node
// Import the map rows the web engine streams (docs/design/WEB_STREAMING.md §3.8) from the Godot game's data, which owns
// them (game/data/usmap.json + game/data/world/*.json; MapForge edits them there). The engine never reads ../game at run
// time: this copies what the current phase needs into src/data/ and records a sha of the sources as the save's dataHash.
//   node tools/import-usmap.mjs                 (from web/)
//   node tools/import-usmap.mjs --check         exit 1 if src/data is stale against the sources
// P1 (Streamed Arizona) needs: the biome/relief/state grids, the interstates, every town and exit row (for `locate`), and
// the streets and placements around the I-10 corridor (Los Angeles .. El Paso). Later phases widen the bounding box.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const WEB = fileURLToPath(new URL('..', import.meta.url));
const SRC = {
  usmap: join(WEB, '../game/data/usmap.json'),
  structures: join(WEB, '../game/data/world/structure_profiles.json'),
  blueprints: join(WEB, '../game/data/world/exit_blueprints.json'),
};
const OUT = join(WEB, 'src/data/usmap.json');
// The P1 corridor in usmap metres (I-10 from Los Angeles to past El Paso, plus margin): streets and placements in here.
const BOX = { x0: -53500, x1: -33000, y0: 3000, y1: 14000 };
// Florida (docs/design/WEB_FLORIDA.md, the start region): the peninsula from the Georgia line to Miami, both coasts.
// Its towns' streets and placements (Jacksonville, Tampa, Miami, Rosewood, the Dry Dock) come in with it.
const BOX_FL = { x0: -7400, x1: 1600, y0: 11200, y1: 22500 };
const BOXES = [BOX, BOX_FL];

for (const p of Object.values(SRC)) if (!existsSync(p)) { console.error(`missing source ${p}`); process.exit(2); }
const raw = Object.fromEntries(Object.entries(SRC).map(([k, p]) => [k, readFileSync(p)]));
const sha = (b) => createHash('sha256').update(b).digest('hex').slice(0, 16);
const dataHash = sha(Buffer.concat([raw.usmap, raw.structures, raw.blueprints]));

if (process.argv.includes('--check')) {
  const cur = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')).meta?.dataHash : null;
  console.log(cur === dataHash ? `up to date (${dataHash})` : `STALE: src/data has ${cur}, sources are ${dataHash}`);
  process.exit(cur === dataHash ? 0 : 1);
}

const d = JSON.parse(raw.usmap);
const S = JSON.parse(raw.structures), B = JSON.parse(raw.blueprints);
const inBox = (p) => BOXES.some((B) => p[0] >= B.x0 && p[0] <= B.x1 && p[1] >= B.y0 && p[1] <= B.y1);
const r1 = (v) => Math.round(v * 10) / 10;
const pt = (p) => [r1(p[0]), r1(p[1])];

const out = {
  meta: {
    note: 'GENERATED by tools/import-usmap.mjs from game/data (read-only source). Do not edit by hand: re-run the import.',
    phase: 'P1+FL', box: BOX, boxes: BOXES, dataHash, sources: Object.fromEntries(Object.entries(raw).map(([k, b]) => [k, sha(b)])),
    counts: { roads: d.roads.length, junctions: d.junctions.length, exits: d.exits.length, towns: d.towns.length, placements: d.placements.length, rivers: d.rivers.length },
  },
  cell_m: d.cell_m, world_offset: d.world_offset, w: d.w, h: d.h,
  legend: d.legend, grid: d.grid, state_legend: d.state_legend, states_grid: d.states_grid, relief: d.relief,
  interstates: d.roads.filter((r) => r.kind === 'interstate').map((r) => ({ id: r.id, nickname: r.nickname, family: r.family, lanes: r.lanes, divided: r.divided, danger: r.danger, surface: r.surface, pts: r.pts.map(pt) })),
  streets: d.roads.filter((r) => r.kind === 'street' && r.pts.some(inBox)).map((r) => ({ id: r.id, lanes: r.lanes, pts: r.pts.map(pt) })),
  // The national county and dirt roads (the World Forge's MAP draws, checks and edits them; the engine reads them at P3).
  roads: d.roads.filter((r) => r.kind === 'county' || r.kind === 'dirt').map((r) => ({ id: r.id, kind: r.kind, lanes: r.lanes, surface: r.surface, danger: r.danger, ...(r.leads_to ? { leads_to: r.leads_to } : {}), pts: r.pts.map(pt) })),
  towns: d.towns.map((t) => ({ id: t.id, name: t.name, kind: t.kind, pos: pt(t.pos), landmark: t.landmark ?? null, landmark_kind: t.landmark_kind ?? null })),
  exits: d.exits.map((e) => ({ id: e.id, highway_id: e.highway_id, exit_number: e.exit_number, name: e.name, archetype: e.archetype, community_tier: e.community_tier,
    service_tags: e.service_tags, risk_rating: e.risk_rating, has_return_ramp: e.has_return_ramp, pos: pt(e.pos), dest: e.dest ? pt(e.dest) : null, ramp_ids: e.ramp_ids ?? [], town_id: e.town_id ?? null })),
  placements: d.placements.filter((p) => inBox(p.pos)).map((p) => ({ id: p.id, building: p.building, pos: pt(p.pos), rot: Math.round(p.rot * 1000) / 1000 })),
  rivers: d.rivers.map((r) => ({ id: r.id, pts: r.pts.map(pt) })),
  structures: S.structures.map((s) => ({ id: s.id, category: s.category, display_name: s.display_name, footprint_m: s.footprint_m, floors: s.floors ?? 1, enterable: !!s.enterable })),
  exit_archetypes: B.exit_archetypes.map((a) => ({ id: a.id, name: a.name, tier_default: a.tier_default, sign_style: a.sign_style, structures_hint: a.structures_hint, service_tags: a.service_tags })),
};
// Rows the World Forge authored (web/forge.html; meta.forge.edits in the current file) win over the import: an edited
// row is carried over as it is, a removed one stays removed, a forge-only collection (rails) keeps its rows.
let carried = 0;
const prev = existsSync(OUT) ? JSON.parse(readFileSync(OUT, 'utf8')) : null;
if (prev?.meta?.forge?.edits) {
  out.meta.forge = prev.meta.forge;
  for (const [key, when] of Object.entries(prev.meta.forge.edits)) {
    const [coll, ...rest] = key.split('/'), id = rest.join('/');
    out[coll] ??= [];
    const i = out[coll].findIndex((r) => r.id === id);
    if (String(when).startsWith('removed')) { if (i >= 0) { out[coll].splice(i, 1); carried++; } continue; }
    const row = prev[coll]?.find((r) => r.id === id);
    if (!row) continue;
    if (i >= 0) out[coll][i] = row; else out[coll].push(row);
    carried++;
  }
}
writeFileSync(OUT, JSON.stringify(out));
if (carried) console.log(`carried over ${carried} World Forge row edit(s) (meta.forge.edits)`);
const kb = (JSON.stringify(out).length / 1024).toFixed(0);
console.log(`wrote src/data/usmap.json (${kb} KB, dataHash ${dataHash}): ${out.interstates.length} interstates, ${out.streets.length} streets, ${out.towns.length} towns, ${out.exits.length} exits, ${out.placements.length} placements, ${out.structures.length} structures`);
