#!/usr/bin/env node
// Regenerate docs/COMMANDS.md from the live COMMANDS table (needs `npm run dev` + a game tab).
//   node tools/gen-commands.mjs
import { writeFileSync, mkdirSync } from 'node:fs';

const BASE = process.env.DL_URL ?? 'http://localhost:3141';
const r = await fetch(`${BASE}/agent/cmd`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ cmd: 'help' }) }).then((x) => x.json());
if (!r.ok) { console.error(r); process.exit(1); }
const groups = {};
for (const c of r.commands) (groups[c.group] ??= []).push(c);
let md = '# DSOA agent commands\n\n_Generated by `node tools/gen-commands.mjs` from the live `COMMANDS` table in `src/agent/api.js`. Do not edit by hand._\n\n';
md += 'Arg notation: `name:type` required, `name?:type` optional, `a|b` enum.\n\n';
for (const [g, list] of Object.entries(groups)) {
  md += `## ${g}\n\n| command | args | what it does |\n|---|---|---|\n`;
  for (const c of list) md += `| \`${c.cmd}\` | \`${c.args.replace(/\|/g, '\\|')}\` | ${c.desc.replace(/\|/g, '\\|')} |\n`;
  md += '\n';
}
mkdirSync('docs', { recursive: true });
writeFileSync('docs/COMMANDS.md', md);
console.log(`wrote docs/COMMANDS.md (${r.commands.length} commands)`);
